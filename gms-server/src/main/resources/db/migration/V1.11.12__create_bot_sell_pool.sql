-- =============================================================================
-- 摆摊出售机器人（SELLING_MERCHANT_BOT）的货架物品池
--
-- 数据由 SoloMapling 的 itemConfig/*.yaml 一次性导出，之后只读数据库，不再有 YAML 回退。
-- 导出范围：scrolls.yaml（普通卷轴）、darkscrolls.yaml（暗黑卷轴）、
--           thief.yaml 的 Stars 段（飞镖）、useables.yaml 的 Potions 段（药水）。
--
-- price 是「每格/每组」的价钱：买家付 price * 组数，拿到 item.quantity * 组数 个。
-- qty_* 是每格的物品数量（药水按瓶、飞镖按个、卷轴固定 1）。
-- weight 是同池抽签权重，越高越容易被摆出来。
-- =============================================================================

CREATE TABLE IF NOT EXISTS `bot_sell_item_pool` (
  `id` INT(11) NOT NULL AUTO_INCREMENT COMMENT '主键',
  `category` VARCHAR(32) NOT NULL COMMENT 'scroll/darkscroll/star/potion',
  `item_id` INT(11) NOT NULL COMMENT '物品 ID',
  `price` INT(11) NOT NULL DEFAULT 0 COMMENT '每格单价（mesos）',
  `qty_min` SMALLINT NOT NULL DEFAULT 1 COMMENT '每格数量下限',
  `qty_max` SMALLINT NOT NULL DEFAULT 1 COMMENT '每格数量上限',
  `weight` INT(11) NOT NULL DEFAULT 100 COMMENT '抽签权重',
  `enabled` TINYINT(1) NOT NULL DEFAULT 1 COMMENT '1=参与抽取',
  `note` VARCHAR(128) NOT NULL DEFAULT '' COMMENT '物品名/备注',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_bot_sell_pool` (`category`, `item_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='机器人摆摊出售物品池';

